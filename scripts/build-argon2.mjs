// Assembles packages/crypto/argon2/argon2.wat into src/argon2-wasm.ts with the
// pinned wabt (decisions/0028). The output is committed; `--check` rebuilds in
// memory and fails if the committed bytes differ, which is what CI runs, so
// the module in every build is exactly what the source says.

import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'

import wabtInit from 'wabt'

const ROOT = new URL('../packages/crypto/', import.meta.url).pathname
const SOURCE = `${ROOT}argon2/argon2.wat`
const OUT = `${ROOT}src/argon2-wasm.ts`

const wabt = await wabtInit()
const module = wabt.parseWat('argon2.wat', readFileSync(SOURCE, 'utf8'), {})
module.validate()
const { buffer } = module.toBinary({ log: false, write_debug_names: false })
module.destroy()
const bytes = Buffer.from(buffer)
const sha256 = createHash('sha256').update(bytes).digest('hex')

const text = `// Generated by scripts/build-argon2.mjs from packages/crypto/argon2/argon2.wat
// with wabt 1.0.39. Do not edit: change the .wat and run the script.
// CI rebuilds it and fails on any difference.

export const ARGON2_WASM_SHA256 = '${sha256}'

export const ARGON2_WASM_BASE64 =
  '${bytes.toString('base64')}'
`

if (process.argv.includes('--check')) {
  const committed = readFileSync(OUT, 'utf8')
  if (committed !== text) {
    console.error(`argon2-wasm.ts does not match argon2.wat (expected sha256 ${sha256}). Run: node scripts/build-argon2.mjs`)
    process.exit(1)
  }
  console.log(`argon2-wasm.ts matches its source (sha256 ${sha256}, ${bytes.length} bytes)`)
} else {
  writeFileSync(OUT, text)
  console.log(`wrote ${OUT} (sha256 ${sha256}, ${bytes.length} bytes)`)
}
