// Regenerates packages/core/src/psl-data.ts from the Public Suffix List.
//
// The extension matches logins by registrable domain (decisions/0029), so it
// needs the list; it is bundled, never fetched at run time. Run this now and
// then and commit the result:  node scripts/update-psl.mjs [path-to-local.dat]
//
// Rules are stored in ASCII (punycode), the form URL.hostname gives.

import { readFileSync, writeFileSync } from 'node:fs'
import { domainToASCII } from 'node:url'

const source = process.argv[2]
  ? readFileSync(process.argv[2], 'utf8')
  : await (await fetch('https://publicsuffix.org/list/public_suffix_list.dat')).text()

const rules = []
for (const raw of source.split('\n')) {
  const line = raw.trim().split(/\s/)[0]
  if (!line || line.startsWith('//')) continue
  const bang = line.startsWith('!') ? '!' : ''
  const body = bang ? line.slice(1) : line
  const ascii = body.split('.').map((l) => (l === '*' ? l : domainToASCII(l) || l)).join('.')
  rules.push(bang + ascii.toLowerCase())
}
if (rules.length < 5000) throw new Error(`only ${rules.length} rules: not the real list?`)

const out = `// Generated by scripts/update-psl.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit.
//
// The Public Suffix List (https://publicsuffix.org/), ICANN and private
// sections, ${rules.length} rules, in ASCII. It is subject to the Mozilla Public
// License, v. 2.0: https://mozilla.org/MPL/2.0/.

export const PSL_RULES = ${JSON.stringify(rules.join('\n'))}
`
writeFileSync(new URL('../packages/core/src/psl-data.ts', import.meta.url), out)
console.log(`psl-data.ts: ${rules.length} rules`)
